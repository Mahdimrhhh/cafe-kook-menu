export function getRandomMessage() {
    const index = Math.floor(Math.random() * motivationalMessages.length);
    return motivationalMessages[index];
}

export function getRandomMessageAvoiding(lastText) {
    if (motivationalMessages.length <= 1) return motivationalMessages[0];
    let msg;
    let attempts = 0;
    do {
        msg = getRandomMessage();
        attempts++;
    } while (msg.text === lastText && attempts < 10);
    return msg;
}
